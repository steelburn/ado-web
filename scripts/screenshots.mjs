export function hasGlyph(char) {
  return Object.prototype.hasOwnProperty.call(GLYPHS, char);
}

/** Upper-cases and maps unknown characters (é, →, …) to '-' so text always renders. */
export function sanitizeLabel(text) {
  return String(text)
    .toUpperCase()
    .split('')
    .map((char) => (hasGlyph(char) ? char : '-'))
    .join('');
}

export function measureText(text, scale) {
  if (!text.length) return 0;
  return (text.length * (GLYPH_W + GLYPH_GAP) - GLYPH_GAP) * scale;
}

function fillRect(rgb, width, height, x, y, w, h, color) {
  const x0 = Math.max(0, Math.round(x));
  const y0 = Math.max(0, Math.round(y));
  const x1 = Math.min(width, Math.round(x + w));
  const y1 = Math.min(height, Math.round(y + h));
  for (let yy = y0; yy < y1; yy++) {
    for (let xx = x0; xx < x1; xx++) {
      const i = (yy * width + xx) * 3;
      rgb[i] = color[0];
      rgb[i + 1] = color[1];
      rgb[i + 2] = color[2];
    }
  }
}

export function drawText(rgb, width, height, text, x, y, scale, color) {
  String(text).split('').forEach((char, i) => {
    const rows = GLYPHS[char];
    if (!rows) return;
    const cx = x + i * (GLYPH_W + GLYPH_GAP) * scale;
    rows.forEach((row, r) => {
      for (let c = 0; c < GLYPH_W; c++) {
        if ((row >> (GLYPH_W - 1 - c)) & 1) {
          fillRect(rgb, width, height, cx + c * scale, y + r * scale, scale, scale, color);
        }
      }
    });
  });
}

const CRC_TABLE = (() => {
  const table = new Int32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    table[n] = c;
  }
  return table;
})();

function crc32(buffer) {
  let c = -1;
  for (let i = 0; i < buffer.length; i++) c = CRC_TABLE[(c ^ buffer[i]) & 0xff] ^ (c >>> 8);
  return (c ^ -1) >>> 0;
}

function pngChunk(type, data) {
  const length = Buffer.alloc(4);
  length.writeUInt32BE(data.length, 0);
  const body = Buffer.concat([Buffer.from(type, 'latin1'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body), 0);
  return Buffer.concat([length, body, crc]);
}

/** Encodes raw RGB bytes as an 8-bit truecolour PNG. Pure + deterministic. */
export function encodePng({ width, height, rgb, texts = {} }) {
  const stride = width * 3;
  const raw = Buffer.alloc((stride + 1) * height);
  for (let y = 0; y < height; y++) {
    raw[y * (stride + 1)] = 0; // filter: none
    rgb.copy(raw, y * (stride + 1) + 1, y * stride, (y + 1) * stride);
  }

  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 2; // colour type: truecolour
  ihdr[10] = 0; // deflate
  ihdr[11] = 0; // adaptive filtering
  ihdr[12] = 0; // no interlace

  const parts = [
    Buffer.from(PNG_SIGNATURE),
    pngChunk('IHDR', ihdr),
    pngChunk('IDAT', deflateSync(raw, { level: 9 })),
  ];
  for (const [keyword, value] of Object.entries(texts)) {
    parts.push(
      pngChunk(
        'tEXt',
        Buffer.concat([
          Buffer.from(String(keyword), 'latin1'),
          Buffer.from([0]),
          Buffer.from(String(value), 'latin1'),
        ])
      )
    );
  }
  parts.push(pngChunk('IEND', Buffer.alloc(0)));
  return Buffer.concat(parts);
}

const BG = [11, 14, 20];
const FRAME = [35, 42, 59];
const ACCENT = [43, 143, 224];
const INK = [230, 233, 240];
const DIM = [139, 147, 167];

/**
 * Renders the committed stand-in PNG for a shot: brand-dark plate, hairline
 * frame and the shot id, size and capture pointer. Carries the tEXt marker so
 * `placeholderId()` can prove it is not a real capture.
 */
export function placeholderPng({
  id,
  width = 1440,
  height = 900,
  note = 'CAPTURE GUIDE: ASSETS/IMG/SCREENSHOTS/README.MD',
}) {
  const rgb = Buffer.alloc(width * height * 3);
  fillRect(rgb, width, height, 0, 0, width, height, BG);

  const inset = Math.max(12, Math.round(width / 90));
  const edge = Math.max(2, Math.round(width / 480));
  fillRect(rgb, width, height, inset, inset, width - inset * 2, edge, FRAME);
  fillRect(rgb, width, height, inset, height - inset - edge, width - inset * 2, edge, FRAME);
  fillRect(rgb, width, height, inset, inset, edge, height - inset * 2, FRAME);
  fillRect(rgb, width, height, width - inset - edge, inset, edge, height - inset * 2, FRAME);

  const lines = [
    { text: 'PLACEHOLDER', scale: Math.max(4, Math.round(width / 144)), color: ACCENT },
    { text: sanitizeLabel(id), scale: Math.max(3, Math.round(width / 240)), color: INK },
    { text: sanitizeLabel(width + ' X ' + height + ' PNG'), scale: Math.max(2, Math.round(width / 360)), color: DIM },
    { text: sanitizeLabel(note), scale: Math.max(2, Math.round(width / 520)), color: DIM },
  ];

  const lineHeights = lines.map((line) => GLYPH_H * line.scale);
  const gap = Math.round(width / 120);
  const blockHeight = lineHeights.reduce((sum, h) => sum + h, 0) + gap * (lines.length - 1);

  let y = Math.round((height - blockHeight) / 2);
  lines.forEach((line, i) => {
    const text = String(line.text);
    const x = Math.max(0, Math.round((width - measureText(text, line.scale)) / 2));
    drawText(rgb, width, height, text, x, y, line.scale, line.color);
    y += lineHeights[i] + gap;
  });

  return encodePng({
    width,
    height,
    rgb,
    texts: { [MARKER_KEYWORD]: MARKER_VALUE + ':' + id },
  });
}

/* ── HTML scanning ────────────────────────────────────────── */

/**
 * Extracts every `<figure … data-shot="…">…</figure>` from a page: the wiring
 * the tests compare against the manifest.
 */
export function scanShotFigures(html) {
  const figures = [];
  const figureRe = /<figure\b([^>]*\bdata-shot="([^"]+)"[^>]*)>([\s\S]*?)<\/figure>/g;
  let match;
  while ((match = figureRe.exec(html)) !== null) {
    const [, attrs, id, body] = match;
    const imgRe = /<img\b([^>]*)>/.exec(body);
    const imgAttrs = imgRe ? imgRe[1] : null;
    const attr = (source, name) => {
      if (!source) return null;
      const found = new RegExp('\\b' + name + '="([^"]*)"').exec(source);
      return found ? found[1] : null;
    };
    figures.push({
      id,
      state: attr(attrs, 'data-state'),
      src: attr(imgAttrs, 'src'),
      alt: attr(imgAttrs, 'alt'),
      width: attr(imgAttrs, 'width'),
      height: attr(imgAttrs, 'height'),
      hasImg: Boolean(imgRe),
      caption: /<figcaption[^>]*>([\s\S]*?)<\/figcaption>/.exec(body)
        ? /<figcaption[^>]*>([\s\S]*?)<\/figcaption>/
            .exec(body)[1]
            .replace(/<[^>]+>/g, ' ')
            .replace(/\s+/g, ' ')
            .trim()
        : null,
    });
  }
  return figures;
}
