/* ═══════════════════════════════════════════════════════════
   Screenshot library — shared helpers
   ═══════════════════════════════════════════════════════════
   Single source of truth: `assets/img/screenshots/manifest.json` declares every
   marketing screenshot (id, file, intrinsic size, alt/caption copy, which page
   uses it, and the capture recipe).

   index.html / deck.html reference a shot by id:

     <figure class="shot" data-shot="backlog-tree" data-state="placeholder">
       <img src="/assets/img/screenshots/backlog-tree.png?v=<SITE_VERSION>" ...>
       <figcaption>…</figcaption>
     </figure>

   `data-state` mirrors the manifest `status`:
     "placeholder" → the committed PNG is generated by make-screenshots.mjs and
                     the page only renders the caption card (the placeholder
                     raster is never displayed on the live site).
     "captured"    → a real screenshot is committed and rendered.

   Placeholder PNGs carry a `tEXt` marker, so placeholder-vs-real is verifiable
   without a decoder, a dependency, or any image tooling — same stdlib-only
   approach as the rest of this repo.
*/

import { deflateSync } from 'node:zlib';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const SHOTS_DIR = 'assets/img/screenshots';
export const SHOTS_HREF = '/assets/img/screenshots';
export const MANIFEST_PATH = join(ROOT, SHOTS_DIR, 'manifest.json');
export const GUIDE_PATH = join(ROOT, SHOTS_DIR, 'README.md');

/** tEXt keyword/value written into every generated placeholder PNG. */
export const MARKER_KEYWORD = 'ado-code-shot';
export const MARKER_VALUE = 'placeholder-v1';

/** Pages that may reference shots (`usedOn` values → file names). */
export const PAGES = { index: 'index.html', gallery: 'gallery.html', deck: 'deck.html' };

export const STATES = ['placeholder', 'captured'];
export const SHOT_ID_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
export const SHOT_FILE_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*\.png$/;

/* ── Manifest ─────────────────────────────────────────────── */

export function loadManifest(file = MANIFEST_PATH) {
  return JSON.parse(readFileSync(file, 'utf8'));
}

/**
 * Pure structural validation. Returns an array of human-readable problems
 * (empty array = valid).
 */
export function validateManifest(manifest) {
  const problems = [];
  if (!manifest || typeof manifest !== 'object' || Array.isArray(manifest)) {
    return ['manifest must be a JSON object'];
  }
  if (!Array.isArray(manifest.shots) || manifest.shots.length === 0) {
    return ['manifest.shots must be a non-empty array'];
  }

  const seen = new Set();
  manifest.shots.forEach((shot, i) => {
    if (!shot || typeof shot !== 'object') {
      problems.push('#' + i + ': shot must be an object');
      return;
    }
    const at = typeof shot.id === 'string' ? shot.id : '#' + i;

    if (typeof shot.id !== 'string' || !SHOT_ID_RE.test(shot.id)) {
      problems.push(at + ': id must be a kebab-case slug');
    } else if (seen.has(shot.id)) {
      problems.push(at + ': duplicate id');
    } else {
      seen.add(shot.id);
    }

    if (typeof shot.file !== 'string' || !SHOT_FILE_RE.test(shot.file)) {
      problems.push(at + ': file must be a kebab-case .png name');
    } else if (shot.file !== shot.id + '.png') {
      problems.push(at + ': file must be <id>.png (got ' + shot.file + ')');
    }

    for (const dim of ['width', 'height']) {
      const v = shot[dim];
      if (!Number.isInteger(v) || v < 320 || v > 5120) {
        problems.push(at + ': ' + dim + ' must be an integer between 320 and 5120');
      }
    }

    if (!STATES.includes(shot.status)) {
      problems.push(at + ': status must be one of ' + STATES.join(' | '));
    }

    for (const field of ['title', 'alt', 'caption', 'capture']) {
      const v = shot[field];
      if (typeof v !== 'string' || v.trim().length < 8) {
        problems.push(at + ': ' + field + ' must be a non-trivial string');
      }
    }

    if (typeof shot.alt === 'string') {
      if (/"/.test(shot.alt)) {
        problems.push(at + ': alt must not contain a double quote (it breaks the HTML attribute)');
      }
      if (/(screenshot|image|picture) of/i.test(shot.alt)) {
        problems.push(at + ': alt should describe the UI, not say "' + 'screenshot of"');
      }
    }

    if (!Array.isArray(shot.usedOn) || shot.usedOn.length === 0) {
      problems.push(at + ': usedOn must list at least one page (' + Object.keys(PAGES).join(', ') + ')');
    } else {
      if (new Set(shot.usedOn).size !== shot.usedOn.length) {
        problems.push(at + ': usedOn has duplicates');
      }
      for (const page of shot.usedOn) {
        if (!Object.prototype.hasOwnProperty.call(PAGES, page)) {
          problems.push(at + ': usedOn contains unknown page "' + page + '"');
        }
      }
    }
  });

  return problems;
}

/** Shots whose `usedOn` contains the given page key. */
export function shotsForPage(manifest, page) {
  return manifest.shots.filter((shot) => Array.isArray(shot.usedOn) && shot.usedOn.includes(page));
}

/* ── PNG reading (no decoder: IHDR + tEXt only) ───────────── */

const PNG_SIGNATURE = [137, 80, 78, 71, 13, 10, 26, 10];

/**
 * Minimal PNG walker: signature, IHDR dimensions and tEXt pairs.
 * Never throws — returns { valid: false, reason } for anything unexpected.
 */
export function readPngInfo(buffer) {
  if (!Buffer.isBuffer(buffer) || buffer.length < 8) {
    return { valid: false, reason: 'too small to be a PNG' };
  }
  if (PNG_SIGNATURE.some((byte, i) => buffer[i] !== byte)) {
    return { valid: false, reason: 'bad PNG signature' };
  }

  let offset = 8;
  let width = 0;
  let height = 0;
  const texts = {};
  const types = [];

  while (offset + 8 <= buffer.length) {
    const length = buffer.readUInt32BE(offset);
    const type = buffer.toString('latin1', offset + 4, offset + 8);
    const dataStart = offset + 8;
    if (length > buffer.length || dataStart + length > buffer.length) {
      return { valid: false, reason: 'truncated ' + type + ' chunk' };
    }
    types.push(type);

    if (type === 'IHDR') {
      if (length < 13) return { valid: false, reason: 'short IHDR' };
      width = buffer.readUInt32BE(dataStart);
      height = buffer.readUInt32BE(dataStart + 4);
    } else if (type === 'tEXt') {
      const raw = buffer.toString('latin1', dataStart, dataStart + length);
      const nul = raw.indexOf('\0');
      if (nul > 0) texts[raw.slice(0, nul)] = raw.slice(nul + 1);
    }

    offset = dataStart + length + 4;
    if (type === 'IEND') break;
  }

  if (!width || !height) return { valid: false, reason: 'no IHDR dimensions found' };
  return { valid: true, width, height, texts, types };
}

/** Returns the shot id baked into a generated placeholder PNG, else null. */
export function placeholderId(buffer) {
  const info = readPngInfo(buffer);
  if (!info.valid) return null;
  const value = info.texts[MARKER_KEYWORD];
  if (typeof value !== 'string' || !value.startsWith(MARKER_VALUE)) return null;
  return value.slice(MARKER_VALUE.length).replace(/^:/, '') || null;
}

export function isPlaceholderPng(buffer) {
  return placeholderId(buffer) !== null;
}

